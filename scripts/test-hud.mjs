import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
const root = resolve('.');
const local = (path) => import(pathToFileURL(resolve(root, path)).href);
// A DOM-only event/render check. This does not simulate layout, native validation,
// native dialog focus management or WebGL; those still require a real browser.
const response = await fetch('https://cdn.jsdelivr.net/npm/linkedom@0.18.12/worker.js');
if (!response.ok) throw new Error('Could not load the pinned DOM test helper');
const { parseHTML } = await import(`data:text/javascript;base64,${Buffer.from(await response.text()).toString('base64')}`);
const { window, document } = parseHTML(await readFile('index.html', 'utf8'));
globalThis.window = window; globalThis.document = document;
window.matchMedia = () => ({ matches: false });
const select = document.querySelector('#saved-driver');
Object.defineProperty(select, 'value', {
  configurable: true, get() { return this.querySelector('option[selected]')?.getAttribute('value') || ''; },
  set(value) { this.querySelectorAll('option').forEach(option => { if (option.getAttribute('value') === value) option.setAttribute('selected', ''); else option.removeAttribute('selected'); }); },
});
const form = document.querySelector('#driver-form');
form.reportValidity = () => true;
const name = document.querySelector('#driver-name');
name.setCustomValidity = () => {}; name.reportValidity = () => true;
const dialog = document.querySelector('#race-results');
Object.defineProperty(dialog, 'open', { get() { return this.hasAttribute('open'); } });
dialog.showModal = () => dialog.setAttribute('open', ''); dialog.close = () => dialog.removeAttribute('open');

const { loadEngineHarness } = await local('scripts/engine-harness.mjs');
const { createPhysics, createTrack, createSimulation, createRaceController, createCameraRig, createStartingGrid, createCarLabels, THREE } = await loadEngineHarness();
const { createProfileStore } = await local('js/data/profiles.js');
const { createLobby } = await local('js/race/lobby.js');
const { bindLobbyUI } = await local('js/ui/lobby.js');
const { bindRaceUI } = await local('js/ui/race.js');
const { bindLeaderboard } = await local('js/ui/leaderboard.js');
const { bindControls } = await local('js/ui/controls.js');
const { bindHUD } = await local('js/ui/hud.js');
const hud = bindHUD();
const toggle = (panel) => document.querySelector(`[data-hud-toggle="${panel}"]`);
const visiblePanels = () => [...document.querySelectorAll('[data-hud-panel]')].filter(panel => !panel.hidden);
assert.equal(visiblePanels().length, 0);
toggle('driver').click();
assert.equal(visiblePanels()[0].id, 'hud-driver');
assert.equal(toggle('driver').getAttribute('aria-expanded'), 'true');
toggle('scores').click();
assert.equal(visiblePanels().length, 1);
assert.equal(visiblePanels()[0].id, 'hud-scores');
assert.equal(toggle('driver').getAttribute('aria-expanded'), 'false');
document.querySelector('#hud-scores [data-hud-close]').click();
assert.equal(visiblePanels().length, 0);
toggle('camera').click(); toggle('camera').click();
assert.equal(visiblePanels().length, 0);
toggle('racers').click();
const escape = new window.Event('keydown', { cancelable: true });
Object.defineProperty(escape, 'key', { value: 'Escape' });
document.dispatchEvent(escape);
assert.equal(visiblePanels().length, 0);
document.querySelector('#driver-skip').click();
assert.equal(visiblePanels()[0].id, 'hud-driver');
assert.equal(document.querySelectorAll('#viewport').length, 1);
const ids = [...document.querySelectorAll('[id]')].map(node => node.id);
assert.equal(new Set(ids).size, ids.length, 'Duplicate IDs would break UI bindings');
console.log('PASS HUD: one panel at a time, toggles, close buttons, Escape and driver shortcut');
const values = new Map();
const profiles = createProfileStore({ getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) });
const lobby = createLobby();
const physics = createPhysics();
const track = createTrack(new THREE.Scene(), physics);
const simulation = createSimulation(track.group, physics, { hazards: false });
const race = createRaceController(simulation, profiles);
const lobbyUI = bindLobbyUI(profiles, lobby, { setPaint() {} });
const leaderboardUI = bindLeaderboard(profiles);
let timestamp = 0;
const ui = bindRaceUI(race, profiles, () => lobby.getEntries().filter(row => !row.isBot), state => { lobbyUI.setLocked(state !== 'lobby'); hud.onRaceState(state); }, () => {});
name.value = 'UI Champion';
name.dispatchEvent(new window.Event('input'));
form.dispatchEvent(new window.Event('submit', { bubbles: true, cancelable: true }));
assert.equal(lobby.playerCount, 1);
assert.equal(document.querySelectorAll('#grid-list li').length, 8);
assert.equal(document.querySelectorAll('#leaderboard-list li').length, 1);
document.querySelector('#simulation-toggle').click();
assert.equal(race.state, 'countdown');
assert.equal(visiblePanels().length, 0, 'Starting a race should clear floating panels');
toggle('racers').click();
assert.equal(document.querySelector('#lobby-grid-card').hidden, true);
assert.equal(document.querySelector('#standings-card').hidden, false);
assert.equal(document.querySelector('#driver-fields').disabled, true);
ui.update(timestamp);
assert.equal(document.querySelector('#countdown-value').textContent, '3');
for (let frame = 0; frame < 100 * 60; frame++) { race.update(1 / 60); ui.update(timestamp += 1000 / 60); }
assert.equal(race.state, 'results');
assert.equal(dialog.open, true);
assert.equal(visiblePanels().length, 0);
assert.equal(document.querySelectorAll('#results-rows tr').length, 1);
assert.equal(document.querySelectorAll('#podium-list li').length, 3);
assert.equal(document.querySelector('#profile-wins').textContent, '1 WIN');
assert.equal(document.querySelector('#leaderboard-list strong').textContent, '1');
dialog.close(); document.querySelector('#simulation-toggle').click();
assert.equal(dialog.open, true);
assert.equal(profiles.getData().profiles[0].wins, 1);
document.querySelector('#results-reset').click();
assert.equal(race.state, 'lobby');
assert.equal(dialog.open, false);
assert.equal(document.querySelector('#driver-fields').disabled, false);
console.log('PASS DOM flow: register, join, countdown, results, leaderboard, reopen, reset, unlock');

const canvas = document.createElement('canvas');
document.querySelector('#viewport').append(canvas);
Object.defineProperties(canvas, { clientWidth: { value: 800 }, clientHeight: { value: 600 } });
const rig = createCameraRig(canvas);
rig.resize(800, 600);
const controls = bindControls(rig, () => {});
const car = { root: { position: new THREE.Vector3(20, 0.6, 10) }, body: { velocity: { x: 8, z: 0 } } };
for (let frame = 0; frame < 120; frame++) { rig.updateDirector(car, 1 / 60); rig.controls.update(1 / 60); }
assert.ok(rig.controls.target.x > 10);
assert.ok(rig.camera.zoom > 1.2);
rig.controls.dispatchEvent({ type: 'start' });
assert.equal(rig.directorEnabled, false);
assert.equal(document.querySelector('#director-button').getAttribute('aria-pressed'), 'false');
document.querySelector('#director-button').click();
assert.equal(rig.directorEnabled, true);
controls.setWorld('garage');
const target = rig.controls.target.clone();
rig.updateDirector(car, 1);
assert.ok(rig.controls.target.equals(target));
console.log('PASS camera controls: smooth following, manual override, re-enable, garage isolation');

const viewport = document.querySelector('#viewport');
viewport.getBoundingClientRect = () => ({ width: 800, height: 600 });
const labels = createCarLabels(viewport);
const grid = createStartingGrid(track.group);
const roster = createLobby().getEntries();
roster[0] = { ...roster[0], name: '<b>Local racer</b>', isBot: false };
grid.update(roster);
const camera = new THREE.PerspectiveCamera(50, 800 / 600, 0.1, 200);
camera.position.set(0, 65, 65); camera.lookAt(0, 0, 0); camera.updateMatrixWorld();
labels.update(grid.getLabelTargets(), [], camera);
assert.equal(viewport.querySelectorAll('.car-label').length, 8);
assert.equal(viewport.querySelectorAll('.car-label-arrow').length, 8);
assert.ok([...viewport.querySelectorAll('.car-label-arrow')].every(arrow => arrow.textContent === '▼'));
const first = viewport.querySelector('.car-label');
const firstArrow = viewport.querySelector('.car-label-arrow');
// The arrow tip follows the physical car's projected anchor even when text is
// displaced to avoid overlap. This verifies attachment without a layout engine.
const anchor = grid.getLabelTargets()[0].root.getWorldPosition(new THREE.Vector3());
anchor.y += 2.1; anchor.project(camera);
const xy = firstArrow.style.transform.match(/translate\(([-\d.]+)px, ([-\d.]+)px\)/).slice(1).map(Number);
assert.ok(Math.abs(xy[0] + 8 - (anchor.x * 0.5 + 0.5) * 800) < 0.1);
assert.ok(Math.abs(xy[1] + 16 - (-anchor.y * 0.5 + 0.5) * 600) < 0.1);
assert.equal(first.querySelector('.car-label-name').textContent, '<b>Local racer</b>');
assert.equal(first.querySelectorAll('b').length, 0);
assert.equal(first.querySelector('.car-label-rank').textContent, 'P1');
assert.equal(first.dataset.local, 'true');
labels.update(grid.getLabelTargets(), [{ id: roster[0].id, position: 3, status: 'racing' }], camera);
assert.equal(first.querySelector('.car-label-rank').textContent, 'P3');
labels.update(grid.getLabelTargets(), [], camera, false);
assert.equal(viewport.querySelector('.car-label-layer').hidden, true);
labels.update(grid.getLabelTargets(), [], camera);
assert.equal(viewport.querySelector('.car-label-layer').hidden, false);
const labelTarget = grid.getLabelTargets()[0];
labelTarget.root.position.set(0, 0, 1000);
labels.update([labelTarget], [{ id: roster[0].id, position: 3, status: 'dnf' }], camera);
assert.equal(viewport.querySelectorAll('.car-label').length, 1);
assert.equal(first.hidden, true);
assert.equal(firstArrow.hidden, true);
assert.equal(viewport.querySelectorAll('.car-label-arrow').length, 1);
assert.equal(first.querySelector('.car-label-rank').textContent, 'DNF');
grid.update(roster); labels.update(grid.getLabelTargets(), [], camera);
assert.equal(viewport.querySelectorAll('.car-label').length, 8);
labels.dispose(); grid.dispose();
assert.equal(viewport.querySelectorAll('.car-label-layer').length, 0);
console.log('PASS car labels: grid names, safe text, current ranks, garage hide, offscreen hide, reset and cleanup');

hud.dispose(); controls.dispose(); rig.dispose(); ui.dispose(); leaderboardUI.dispose(); lobbyUI.dispose(); race.dispose(); simulation.dispose(); physics.dispose();
console.log('\n4 HUD / DOM integration checks passed. Native browser layout and focus are not simulated.');
